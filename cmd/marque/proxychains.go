package main

import (
	"fmt"
	"io"
	"net"

	"github.com/spf13/cobra"
)

func newProxychainsConfigCmd() *cobra.Command {
	var listenAddr string

	cmd := &cobra.Command{
		Use:   "proxychains-config",
		Short: "Emit a ready-to-use proxychains config snippet",
		RunE: func(cmd *cobra.Command, args []string) error {
			return printProxychainsConfig(cmd.OutOrStdout(), listenAddr)
		},
	}

	// Default matches marque proxy's own default --listen, so the
	// common case (nobody overrode either) just works together.
	cmd.Flags().StringVar(&listenAddr, "listen", defaultProxyAddr, "the address marque proxy is (or will be) listening on")
	return cmd
}

func printProxychainsConfig(w io.Writer, listenAddr string) error {
	host, port, err := net.SplitHostPort(listenAddr)
	if err != nil {
		return fmt.Errorf("invalid --listen address %q: %w", listenAddr, err)
	}
	fmt.Fprintln(w, "# generated by `marque proxychains-config`")
	fmt.Fprintln(w, "[ProxyList]")
	fmt.Fprintf(w, "socks5 %s %s\n", host, port)
	return nil
}
